// Generates packages/core/src/map-data.ts from Natural Earth (world-atlas, public domain).
// Usage: node scripts/gen-map.mjs  (requires world-atlas and topojson-client, installed ad hoc)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const { feature } = require('topojson-client');
const fc = feature(topo, topo.objects.countries);
const want = { '682': 'SAU', '400': 'JOR', '368': 'IRQ', '414': 'KWT', '634': 'QAT', '784': 'ARE', '512': 'OMN', '887': 'YEM', '048': 'BHR', '818': 'EGY', '376': 'ISR', '275': 'PSE', '760': 'SYR', '364': 'IRN', '729': 'SDN', '232': 'ERI' };
const round = (n) => Math.round(n * 100) / 100;
const out = {};
for (const f of fc.features) {
  const code = want[f.id];
  if (!code) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  for (const p of polys) {
    const ring = p[0].map(([x, y]) => [round(x), round(y)]).filter((pt, i, a) => i === 0 || pt[0] !== a[i - 1][0] || pt[1] !== a[i - 1][1]);
    if (ring.length > 3) rings.push(ring);
  }
  out[code] = rings;
}
const ts = `/* Generated by scripts/gen-map.mjs from Natural Earth 1:50m (public domain) via world-atlas. Do not edit. */
export const COUNTRY_RINGS: Record<string, [number, number][][]> = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../packages/core/src/map-data.ts', import.meta.url), ts);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.reduce((n, r) => n + r.length, 0)])));
